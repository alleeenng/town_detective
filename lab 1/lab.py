c = int(input("Введите значение c:"))              # ввод c (целое)
d = int(input("Введите значение d:"))              # ввод d (целое)
e = int(input("Введите значение e (не равно 0):")) # ввод e, по условию e ≠ 0
result = a - (-b) * c + d // e ** 2   # первичное вычисление по формуле (промежуточное)
minus_b = -b                          # шаг 1: значение -b
bc = -b * c                           # шаг 2: значение -b * c
